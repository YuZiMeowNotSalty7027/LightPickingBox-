fun fallbackIconForCategory(name: String): String {
    return when {
        name.contains("数码") || name.contains("电子") -> "ic_headphones"
        name.contains("衣") || name.contains("穿") -> "ic_shirt"
        name.contains("食") || name.contains("饮") -> "ic_coffee"
        name.contains("护") || name.contains("药") -> "ic_heart_pulse"
        name.contains("工具") -> "ic_wrench"
        name.contains("书") || name.contains("文") -> "ic_book_open"
        else -> "ic_boxes"
    }
}
